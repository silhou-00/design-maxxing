#!/usr/bin/env node
/* ═══════════════════════════════════════════════════════════════════════════
   build-sections.mjs — generate one scrollable section per technique

     node _shared/build-sections.mjs <technique> | --all

   Reads sections.json. Each entry is a full-height, genuinely scrollable
   demonstration of ONE technique, plus the notes that explain it.

   WHY SEPARATE FILES. These techniques cannot share a document: pinned
   scenes, snap containers and smooth scroll all want to own the scroll
   container, and they fight. `specimens/index.html` stays the flat overview;
   these are the working demonstrations.

   Every section is wired to `_shared/audit.js`, which checks it against
   engine.md §6 — composite-only properties, no scroll listener, the mandatory
   @supports fallback, and a prefers-reduced-motion collapse.
   ═════════════════════════════════════════════════════════════════════════ */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const OUT = join(ROOT, 'sections');
const esc = s => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const q = s => String(s ?? '').replace(/"/g, '&quot;');

const SPECS = JSON.parse(readFileSync(join(ROOT, 'sections.json'), 'utf8'));

const rateClass = r => r === '●' ? '' : r === '○' ? '' : r === '⚠' ? ' warn' : ' no';

function build(key) {
  const S = SPECS[key];
  if (!S) return `no spec for "${key}"`;

  const data = [
    `data-technique="${q(key)}"`,
    `data-rating="${q(S.rating || '')}"`,
    `data-timeline="${q(S.timeline || 'view')}"`,
    S.fallbackSelector ? `data-fallback-selector="${q(S.fallbackSelector)}"` : '',
    S.compositeExempt ? `data-composite-exempt="${q(S.compositeExempt)}"` : '',
  ].filter(Boolean).join('\n      ');

  const list = a => (a || []).map(x => `    <li>${x}</li>`).join('\n');

  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>${esc(S.title)} — Scroll Section</title>
<link rel="stylesheet" href="../_shared/sheet.css">
<style>
/* ═══ ${key.toUpperCase()} ═══════════════════════════════════════════════
   GENERATED by _shared/build-sections.mjs from sections.json.
   Edit the spec, then rebuild. Hand edits here are lost.

   Mechanism : ${S.mechanism}
   Rating    : ${S.rating}   ${S.ratingNote || ''}
   Cost      : ${S.cost}
   ═════════════════════════════════════════════════════════════════════════ */
${S.css}

/* ── the fallback engine.md §6 calls mandatory, not optional ───────────── */
${S.fallback}

/* ── WCAG 2.3.3 ────────────────────────────────────────────────────────── */
${S.reducedMotion}
</style>
</head>
<body ${data}>

<nav class="bar">
  <a href="../specimens/index.html">← all techniques</a>
  <span>${esc(key)}</span>
  <span class="rate${rateClass(S.rating)}">${esc(S.rating)} ${esc(S.ratingLabel || '')}</span>
  <span class="sp"></span>
  <a href="../techniques/${esc(key)}.md">technique doc</a>
  <a href="#audit">self-audit</a>
</nav>

<div class="intro">
  <h1>${esc(S.title)}</h1>
  <p class="blurb">${S.blurb}</p>
  <div class="facts">
    <span>Binding <b>${esc(S.binding)}</b></span>
    <span>Mechanism <b>${esc(S.mechanism)}</b></span>
    <span>Cost <b>${esc(S.cost)}</b></span>
    <span>Risk <b>${esc(S.risk)}</b></span>
  </div>
</div>

<main>
  <div class="demo" data-label="live — scroll it">
${S.markup}
  </div>
</main>

<div class="notes">
  <h2>The craft</h2>
  ${S.craft}

  <h2>Implementation</h2>
<pre>${esc(S.snippet)}</pre>

  <h2>When not to use it</h2>
  <ul>
${list(S.avoid)}
  </ul>

  <h2>Style packs</h2>
  <p>${S.packs}</p>

  <h2 id="audit">Self-audit <span style="float:right;font-weight:500;text-transform:none;letter-spacing:0;color:#7a7a85">measured against engine.md §6</span></h2>
  <p>Every row is computed from this page: its real stylesheet, its real animations. The rules being
  checked are the engine's own — <b>composite-only properties</b>, <b>no window scroll listener</b>,
  <b>the mandatory <code>@supports</code> fallback</b>, and a <b>reduced-motion collapse</b>. They
  were prose that nothing enforced.</p>
  <table class="spec" id="auditTable">
    <tr><th>Check</th><th>Measured</th><th>Required</th><th></th></tr>
  </table>
  <p id="auditSummary"></p>
</div>

<footer>
  <a href="../specimens/index.html">← all ${Object.keys(SPECS).length} techniques</a> ·
  <a href="../techniques/${esc(key)}.md">${esc(key)}.md</a> ·
  <a href="../compatibility.md">compatibility matrix</a>
</footer>

${S.script ? `<script>
${S.script}
</script>` : ''}
<script src="../_shared/audit.js"></script>
</body>
</html>
`;
  if (!existsSync(OUT)) mkdirSync(OUT, { recursive: true });
  writeFileSync(join(OUT, key + '.html'), html, 'utf8');
  return html.length;
}

const args = process.argv.slice(2);
const keys = args.includes('--all') ? Object.keys(SPECS) : args.filter(a => !a.startsWith('--'));
if (!keys.length) { console.error('usage: build-sections.mjs <technique> | --all'); process.exit(1); }
for (const k of keys) {
  const r = build(k);
  console.log(typeof r === 'number' ? String(r).padStart(7) + ' bytes   ' + k : '   ' + r);
}
